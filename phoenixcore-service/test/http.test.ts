import {ReviewFixture} from './review-fixture.ts';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {generateKeyPairSync,randomBytes,randomUUID,sign} from 'node:crypto';
import {once} from 'node:events';
import {openSqlite,initialize,defaultSettings} from '../src/db.ts';
import {application,hash,configuration} from '../src/server.ts';
import {editorRole} from '../src/codex.ts';
import {Discord,deliverNext,type Config} from '../src/discord.ts';

test('Codex sign-in, current directory, player edit, Discord approval, and staff award through HTTP',async t=>{
  const db=openSqlite(':memory:');
  const ids={guild:'800000000000000001',owner:'800000000000000002',writer:'800000000000000003',judge:'800000000000000004',extra:'800000000000000005',app:'800000000000000006',role:'800000000000000007'};
  const {publicKey,privateKey}=generateKeyPairSync('ed25519');
  const config:Config={service:'http://localhost:4100',dashboard:'https://codex.example/convergence-codex/phoenixcore/',owner:ids.owner,guild:ids.guild,clientId:ids.app,
    publicKey:publicKey.export({type:'spki',format:'der'}).subarray(-32).toString('hex'),clientSecret:'example',token:'bot-test'};
  const origin=new URL(config.dashboard).origin;
  await initialize(db,ids.guild);
  const members=Object.entries(ids).filter(([k])=>['writer','owner','judge','extra'].includes(k)).map(([k,id])=>({user:{id,username:k,global_name:k.toUpperCase()},roles:k==='judge'?[ids.role]:[]}));
  const fixture=new ReviewFixture(config);
  const discord=new Discord(config,async(u,init)=>{
    const path=new URL(String(u)).pathname;
    if(path.endsWith('/oauth2/token')) return Response.json({access_token:new URLSearchParams(String(init?.body)).get('code')});
    if(path.endsWith('/users/@me')) return Response.json({id:new Headers(init?.headers).get('Authorization')!.slice(7)});
    if(path.endsWith('/members'))return Response.json(members);
    if(path.includes('/members/')){const m=members.find(x=>x.user.id===path.split('/').pop());return Response.json(m||{}, {status:m?200:404});}
    return fixture.respond(path,init);
  });
  const server=application(db,config,discord);server.listen(0,'127.0.0.1');await once(server,'listening');
  t.after(async()=>{await new Promise<void>(res=>server.close(()=>res()));await db.close();});
  const base='http://127.0.0.1:'+((server.address()) as any).port;
  const get=(p:string,opts:RequestInit={})=>fetch(base+p,{redirect:'manual',...opts});
  const post=(p:string,body:any,s='',from=origin)=>get(p,{method:'POST',headers:{origin:from,'content-type':'application/json',...(s?{Authorization:'Bearer '+s}:{})},body:JSON.stringify(body)});
  async function login(id:string) {
    const verifier=randomBytes(32).toString('base64url');
    const a=await get('/auth/start?challenge='+hash(verifier));
    const auth=new URL(a.headers.get('location')!);
    assert.equal(auth.origin,'https://discord.com');assert.equal(auth.searchParams.get('scope'),'identify');
    const cookie=a.headers.get('set-cookie')!.split(';')[0];
    const callback='/auth/callback?state='+auth.searchParams.get('state')+'&code='+id;
    assert.equal((await get(callback)).status,403);
    const cb=await get(callback,{headers:{cookie}});
    const uri=new URL(cb.headers.get('location')!);
    if(uri.hash==='#member-required')return '';
    assert.equal(uri.origin,origin);const ticket=uri.hash.slice(7);
    assert.equal((await post('/api/exchange',{ticket,verifier:'x'.repeat(43)})).status,403);
    const exchange=await post('/api/exchange',{ticket,verifier});assert.equal(exchange.status,200);
    assert.equal((await post('/api/exchange',{ticket,verifier})).status,403);
    return (await exchange.json()).session;
  }
  async function state(s:string){const res=await get('/api/state',{headers:{Authorization:'Bearer '+s,origin}});assert.equal(res.status,200);return res.json();}
  async function click(user:string,custom:string){
    const stamp=String(Math.floor(Date.now()/1000));
    const body=JSON.stringify({type:3,application_id:ids.app,user:{id:user},data:{custom_id:custom}});
    const signature=sign(null,Buffer.from(stamp+body),privateKey).toString('hex');
    return (await get('/discord/interactions',{method:'POST',headers:{'x-signature-timestamp':stamp,'x-signature-ed25519':signature},body})).json();
  }
  for(const address of ['/','/phoenixcore/','/phoenixcore/index.html'])assert.equal((await get(address)).headers.get('location'),config.dashboard);
  assert.equal((await get('/api/state')).status,401);
  assert.equal(await login('899999999999999999'),'');
  const writer=await login(ids.writer),owner=await login(ids.owner),judge=await login(ids.judge),extra=await login(ids.extra);
  const publicEntries=()=>get('/api/codex',{headers:{origin}}).then(r=>r.json());
  const access=(s:string)=>get('/api/codex/access',{headers:{Authorization:'Bearer '+s,origin}}).then(r=>r.json());
  const patch={key:'worlds/planet-earth',revision:0,fields:{excerpt:'Revised for the next session.'}};
  assert.deepEqual(await publicEntries(),{entries:[]});
  assert.equal((await post('/api/codex',patch)).status,401);
  assert.equal((await post('/api/codex',patch,owner)).status,403);
  const roleHolder=members.find(m=>m.user.id===ids.owner)!;roleHolder.roles.push(editorRole);
  assert.deepEqual(await access(owner),{canEdit:true});
  assert.equal((await post('/api/codex',patch,owner)).status,200);
  assert.equal((await publicEntries()).entries[0].fields.excerpt,patch.fields.excerpt);
  roleHolder.roles.pop();
  assert.deepEqual(await access(owner),{canEdit:false});
  assert.equal((await post('/api/codex',{...patch,revision:1},owner)).status,403);
  const start=await state(writer);assert.equal(start.players.length,4);assert.equal(start.settings,null);
  const cfg={revision:1,value:{...defaultSettings,judgeRole:ids.role}};
  assert.equal((await post('/api/settings',cfg,judge)).status,403);
  assert.equal((await post('/api/settings',cfg,owner,'https://wrong.example')).status,403);
  assert.equal((await post('/api/settings',cfg,owner)).status,200);
  assert.equal((await state(judge)).actor.isJudge,true);
  const gif=Buffer.from('R0lGODlhAQABAIAAAAAAAP///ywAAAAAAQABAAACAUwAOw==','base64');
  const upload=(data:Buffer,session:string,from=origin)=>get('/api/media',{method:'POST',headers:{origin:from,'content-type':'image/gif',...(session?{authorization:'Bearer '+session}:{})},body:data});
  assert.equal((await upload(gif,'')).status,401);
  assert.equal((await upload(gif,writer,'https://wrong.example')).status,403);
  assert.equal((await upload(Buffer.from('not an image'),writer)).status,415);
  const uploaded=await upload(gif,writer);assert.equal(uploaded.status,201);
  const image=(await uploaded.json()).url, downloaded=await get(new URL(image).pathname);
  assert.equal(downloaded.headers.get('content-type'),'image/gif');assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()),gif);
  const form={id:randomUUID(),kind:'create',fields:{name:'Rin',portrait:image,bpl:'10000',strengths:'Patient\nObservant\nLoyal',weaknesses:'Reckless\nDistrustful\nProud'},reason:'First sheet'};
  assert.ok(Number((await db.query('SELECT expires FROM pc_sessions WHERE id=$1',[hash(writer)]))[0].expires)>Date.now()+29*86400000);
  const firstRequest=await post('/api/requests',form,writer);assert.equal(firstRequest.status,200,await firstRequest.text());
  assert.equal((await state(extra)).requests.length,0);
  assert.equal((await state(owner)).requests.length,1);assert.equal((await state(owner)).characters.length,0);
  await deliverNext(db,discord);
  assert.equal(fixture.cards[0].body.embeds[0].image.url,image);
  const writerRequest=(await state(writer)).requests[0];assert.equal(writerRequest.assessment,undefined);
  assert.equal((await state(judge)).requests[0].assessment.summary,'Ready for staff review');
  assert.equal((await post('/api/requests/'+form.id+'/decision',{action:'approve'},extra)).status,403);
  const control=fixture.cards[0].body.components[0].components[0].custom_id;
  assert.equal((await click(ids.judge,control)).type,4);
  assert.equal((await click(ids.owner,control)).type,7);
  assert.equal((await state(writer)).characters[0].sheet.name,'Rin');
  assert.deepEqual((await state(writer)).favoriteCharacterIds,[]);
  assert.equal((await post('/api/favorites',{characterId:form.id,favorite:true})).status,401);
  assert.equal((await post('/api/favorites',{characterId:form.id,favorite:'yes'},writer)).status,400);
  assert.equal((await post('/api/favorites',{characterId:randomUUID(),favorite:true},writer)).status,404);
  assert.equal((await post('/api/favorites',{characterId:form.id,favorite:true},writer)).status,200);
  assert.equal((await post('/api/favorites',{characterId:form.id,favorite:true},writer)).status,200);
  assert.deepEqual((await state(writer)).favoriteCharacterIds,[form.id]);
  assert.deepEqual((await state(extra)).favoriteCharacterIds,[]);
  assert.equal((await post('/api/favorites',{characterId:form.id,favorite:false},writer)).status,200);
  assert.deepEqual((await state(writer)).favoriteCharacterIds,[]);
  const edit={id:randomUUID(),kind:'edit',characterId:form.id,version:1,fields:{speed:'Patient and precise'},reason:'Correct description'};
  assert.equal((await post('/api/requests',edit,extra)).status,403);
  assert.equal((await post('/api/requests',edit,writer)).status,200);
  assert.equal((await state(writer)).characters[0].sheet.speed,'');await deliverNext(db,discord);
  await click(ids.owner,fixture.cards[1].body.components[0].components[0].custom_id);
  assert.equal((await state(writer)).characters[0].sheet.speed,'Patient and precise');
  const award={id:randomUUID(),kind:'award',characterId:form.id,version:2,award:{percent:'12.5',currency:'20',gear:['Journal']},reason:'Judged session'};
  assert.equal((await post('/api/requests',award,judge)).status,200);
  assert.equal((await state(writer)).characters[0].sheet.bpl,'10000');
  await deliverNext(db,discord);await click(ids.owner,fixture.cards[2].body.components[0].components[0].custom_id);
  assert.equal((await state(writer)).characters[0].sheet.bpl,'11250');
  const training={id:randomUUID(),kind:'training',characterId:form.id,version:3,reason:'A new scene',details:{location:'Dojo',trainingType:'Solo',goals:'Ki control',formula:'One scene at the dojo',claimed:'+100 BPL'}};
  assert.equal((await post('/api/requests',training,writer)).status,200);
  assert.equal((await state(extra)).requests.length,0);
  assert.ok((await state(judge)).requests.some((r:any)=>r.id===training.id));
  const judgmentPath='/api/requests/'+training.id+'/judgment',offer={award:{points:'50'},note:'Approve half the claimed BPL.'};
  assert.equal((await post(judgmentPath,offer,extra)).status,403);
  assert.equal((await post(judgmentPath,offer,judge)).status,200);
  await click(ids.owner,'pc:approve:'+training.id);assert.equal((await state(writer)).characters[0].sheet.bpl,'11300');
  const design={id:randomUUID(),kind:'technique',reason:'For review',fields:{name:'Glide',techType:'SUP',description:'Ride a breeze',requirements:'Ki control',drawbacks:'Needs wind'}};
  assert.equal((await post('/api/requests',design,writer)).status,200);
  assert.equal((await state(extra)).catalogue.length,0);
  const endpoint='/api/requests/'+design.id;
  assert.equal((await (await post(endpoint+'/decision',{action:'decline',note:'Needs a second look.'},judge)).json()).status,'owner_review');
  assert.equal((await post(endpoint+'/decision',{action:'veto'},judge)).status,403);
  assert.equal((await (await post(endpoint+'/decision',{action:'veto'},owner)).json()).status,'approved');
  assert.equal((await state(writer)).requests.find((r:any)=>r.id===design.id).archived,true);
  assert.equal((await post(endpoint+'/remove',{},judge)).status,403);
  assert.equal((await post(endpoint+'/remove',{},owner)).status,200);
  const reader=await state(extra);assert.equal(reader.catalogue[0].fields.name,'Glide');assert.equal(reader.requests.length,0);
  assert.equal((await post('/api/posting',{kind:'tag',characterId:form.id,tag:'rin'},writer)).status,200);
  assert.equal((await state(extra)).characters[0].tag,'rin');
  assert.equal((await state(writer)).posting.tags[0].tag,'rin');assert.equal((await state(extra)).posting.tags.length,0);
  assert.equal((await post('/api/posting',{kind:'tag',characterId:form.id,tag:'mine'},extra)).status,403);
  const filtered={revision:2,value:{...cfg.value,playerRole:ids.role}};
  assert.equal((await post('/api/settings',filtered,owner)).status,200);
  assert.deepEqual((await state(writer)).players.map((p:any)=>p.id),[ids.judge]);assert.equal((await state(writer)).characters.length,0);
  assert.equal((await post('/api/logout',{},writer)).status,200);assert.equal((await get('/api/state',{headers:{Authorization:'Bearer '+writer}})).status,401);
});
test('the service requires a fixed owner identity and an HTTPS or loopback origin',()=>{
  const env={SERVICE_ORIGIN:'https://service.example',DASHBOARD_URL:'https://codex.example/repo/phoenixcore/',DISCORD_CLIENT_ID:'111111111111111111',
    DISCORD_GUILD_ID:'222222222222222222',DISCORD_OWNER_ID:'333333333333333333',DISCORD_PUBLIC_KEY:'00'.repeat(32),DISCORD_TOKEN:'token',DISCORD_CLIENT_SECRET:'secret'};
  assert.equal(configuration(env).owner,env.DISCORD_OWNER_ID);
  assert.throws(()=>configuration({...env,DISCORD_OWNER_ID:''}),/Set DISCORD_OWNER_ID/);
  assert.throws(()=>configuration({...env,SERVICE_ORIGIN:'http://service.example'}),/Use HTTPS/);
});
